using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace OneYaml.SourceGeneration;

// Writes the partial class that holds the metadata. Only public factory methods of the library are used, and
// no reflection, so the result is safe to trim and to compile ahead of time.
internal sealed class Emitter
{
    private const string Services = "global::OneYaml.YamlMetadataServices";
    private const string TypeInfo = "global::OneYaml.YamlTypeInfo";

    private readonly INamedTypeSymbol _context;
    private readonly List<TypeSpec> _types;
    private readonly StringBuilder _out = new();
    private int _indent;
    private int _accessorCount;
    private readonly List<(string Attribute, string Signature)> _accessors = [];

    public Emitter(INamedTypeSymbol context, List<TypeSpec> types)
    {
        _context = context;
        _types = types;
    }

    public string Emit()
    {
        Line("// <auto-generated/>");
        Line("// Metadata for the types listed on the context, written by the OneYaml source generator.");
        Line("#nullable disable");
        Line("#pragma warning disable CS0612, CS0618, CS1591");
        Line();

        var containers = new List<INamedTypeSymbol>();
        for (INamedTypeSymbol? t = _context.ContainingType; t is not null; t = t.ContainingType)
        {
            containers.Insert(0, t);
        }

        bool hasNamespace = !_context.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace)
        {
            Line("namespace " + _context.ContainingNamespace.ToDisplayString());
            Open();
        }

        foreach (INamedTypeSymbol container in containers)
        {
            Line("partial " + Keyword(container) + " " + container.Name);
            Open();
        }

        Line("partial class " + _context.Name);
        Open();
        EmitContext();
        Close();

        foreach (INamedTypeSymbol unused in containers)
        {
            _ = unused;
            Close();
        }

        if (hasNamespace)
        {
            Close();
        }

        return _out.ToString();
    }

    private static string Keyword(INamedTypeSymbol type) => type.TypeKind switch
    {
        TypeKind.Struct => type.IsRecord ? "record struct" : "struct",
        TypeKind.Interface => "interface",
        _ => type.IsRecord ? "record" : "class",
    };

    private void EmitContext()
    {
        bool declaresConstructor = false;
        foreach (IMethodSymbol ctor in _context.InstanceConstructors)
        {
            if (!ctor.IsImplicitlyDeclared)
            {
                declaresConstructor = true;
            }
        }

        bool contextIsPublic = IsPublic(_context);
        string name = _context.Name;
        if (!declaresConstructor)
        {
            Line($"/// <summary>The context with default options.</summary>");
            Line($"public static {name} Default {{ get; }} = new {name}();");
            Line();
            Line($"/// <summary>Creates the context with default options.</summary>");
            Line($"public {name}() : base(null)");
            Open();
            Close();
            Line();
            Line($"/// <summary>Creates the context with the given settings.</summary>");
            Line($"public {name}(global::OneYaml.YamlSerializerOptions options) : base(options)");
            Open();
            Close();
            Line();
        }

        foreach (TypeSpec type in _types)
        {
            EmitProperty(type, contextIsPublic);
            Line();
        }

        Line("/// <inheritdoc/>");
        Line("public override " + TypeInfo + " GetTypeInfo(global::System.Type type)");
        Open();
        foreach (TypeSpec type in _types)
        {
            Line($"if (type == typeof({type.Name}))");
            Open();
            Line($"return this.{type.Property};");
            Close();
        }

        Line("return null;");
        Close();

        foreach ((string attribute, string signature) in _accessors)
        {
            Line();
            Line(attribute);
            Line(signature);
        }
    }

    private static bool IsPublic(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? t = type; t is not null; t = t.ContainingType)
        {
            if (t.DeclaredAccessibility != Accessibility.Public)
            {
                return false;
            }
        }

        return true;
    }

    private void EmitProperty(TypeSpec type, bool contextIsPublic)
    {
        string access = type.Visibility == 3 && contextIsPublic ? "public" : type.Visibility >= 2 ? "internal" : "private";
        string field = "_" + type.Property;
        string info = $"{TypeInfo}<{type.Name}>";
        Line($"private {info} {field};");
        Line();
        Line($"/// <summary>Metadata for <c>{Xml(type.Symbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat))}</c>.</summary>");
        Line($"{access} {info} {type.Property} => {field} ??= {Services}.TryCreateCustomConverterInfo<{type.Name}>(Options) ?? Create{type.Property}();");
        Line();
        Line($"private {info} Create{type.Property}()");
        Open();
        switch (type.Shape)
        {
            case TypeShape.Leaf:
                Line($"return {Services}.CreateValueInfo<{type.Name}>(Options, {Services}.GetBuiltInConverter<{type.Name}>(Options));");
                break;
            case TypeShape.Nullable:
                Line($"return {Services}.CreateNullableInfo<{type.Dependencies[0].Name}>(Options, this.{type.Dependencies[0].Property});");
                break;
            case TypeShape.Enum:
                Line($"return {Services}.CreateEnumInfo<{type.Name}>(Options);");
                break;
            case TypeShape.Array:
                Line($"return {Services}.CreateArrayInfo<{type.Dependencies[0].Name}>(Options, this.{type.Dependencies[0].Property});");
                break;
            case TypeShape.List:
                Line($"return {Services}.CreateListInfo<{type.Dependencies[0].Name}>(Options, this.{type.Dependencies[0].Property});");
                break;
            case TypeShape.HashSet:
                Line($"return {Services}.CreateHashSetInfo<{type.Dependencies[0].Name}>(Options, this.{type.Dependencies[0].Property});");
                break;
            case TypeShape.Dictionary:
                Line($"return {Services}.CreateDictionaryInfo<{type.Dependencies[0].Name}, {type.Dependencies[1].Name}>(Options, this.{type.Dependencies[0].Property}, this.{type.Dependencies[1].Property});");
                break;
            case TypeShape.Interface:
                Line($"return {Services}.CreateInterfaceInfo<{type.Name}, {type.ImplementationName}>(Options, this.{type.Dependencies[0].Property});");
                break;
            case TypeShape.CustomDictionary:
                Line($"return {Services}.CreateCustomDictionaryInfo<{type.Name}, {type.Dependencies[0].Name}, {type.Dependencies[1].Name}>(Options, this.{type.Dependencies[0].Property}, this.{type.Dependencies[1].Property}, static () => new {type.Name}());");
                break;
            case TypeShape.CustomCollection:
                Line($"return {Services}.CreateCustomCollectionInfo<{type.Name}, {type.Dependencies[0].Name}>(Options, this.{type.Dependencies[0].Property}, static () => new {type.Name}());");
                break;
            default:
                EmitObject(type);
                break;
        }

        Close();
    }

    private void EmitObject(TypeSpec type)
    {
        ObjectSpec obj = type.Object!;
        string n = type.Name;
        Line($"var values = new global::OneYaml.YamlObjectInfoValues<{n}>");
        Open();
        switch (obj.Creator)
        {
            case CreatorKind.Parameterless:
                Line($"ObjectCreator = static () => new {n}(){obj.InitializerText},");
                break;
            case CreatorKind.Default:
                Line($"ObjectCreator = static () => default({n}),");
                break;
            case CreatorKind.Constructor:
                EmitConstructorCreator(n, obj);
                break;
            default:
                break;
        }

        Line("PropertyMetadataInitializer = _ => new global::OneYaml.YamlPropertyInfo[]");
        Open();
        for (int i = 0; i < obj.Members.Count; i++)
        {
            EmitMember(type, obj, obj.Members[i]);
        }

        CloseWith("},");
        CloseWith("};");
        Line($"return {Services}.CreateObjectInfo<{n}>(Options, values);");
    }

    private void EmitConstructorCreator(string n, ObjectSpec obj)
    {
        var args = new StringBuilder();
        for (int i = 0; i < obj.Parameters.Count; i++)
        {
            ParameterSpec p = obj.Parameters[i];
            if (i > 0)
            {
                args.Append(", ");
            }

            string slot = $"args[{i.ToString(CultureInfo.InvariantCulture)}]";
            // A missing value stays null in the slot; a value type then takes its default.
            args.Append(p.IsNonNullableValueType ? $"{slot} is null ? default({p.TypeName}) : ({p.TypeName}){slot}" : $"({p.TypeName}){slot}");
        }

        Line($"ConstructorCreator = static args => new {n}({args}){obj.InitializerText},");
        Line("ConstructorParameterMetadataInitializer = static () => new global::OneYaml.YamlParameterInfo[]");
        Open();
        foreach (ParameterSpec p in obj.Parameters)
        {
            string tail = p.HasDefault ? $", true, {p.DefaultText}" : string.Empty;
            Line($"new global::OneYaml.YamlParameterInfo({Literal(p.Name)}, typeof({p.TypeName}){tail}),");
        }

        CloseWith("},");
    }

    private void EmitMember(TypeSpec type, ObjectSpec obj, MemberSpec m)
    {
        string d = type.Name;
        string t = m.TypeName;
        Line($"{Services}.CreatePropertyInfo<{d}, {t}>(new global::OneYaml.YamlPropertyInfoValues<{d}, {t}>");
        Open();
        Line($"Name = {Literal(m.Name)},");
        if (m.SerializedName is not null)
        {
            Line($"SerializedName = {Literal(m.SerializedName)},");
        }

        if (m.IsRequired)
        {
            Line("IsRequired = true,");
        }

        if (m.Order != 0)
        {
            Line($"Order = {m.Order.ToString(CultureInfo.InvariantCulture)},");
        }

        Line($"PropertyTypeInfo = this.{m.Type.Property},");
        if (m.CanRead)
        {
            Line($"Getter = static o => o.{Parser.CodeName(m.Name)},");
        }

        if (m.IgnoreCondition is { } condition)
        {
            string name = condition == 3 ? "WhenWritingNull" : condition == 2 ? "WhenWritingDefault" : "Never";
            Line($"IgnoreCondition = global::OneYaml.YamlIgnoreCondition.{name},");
        }

        string target = obj.IsStruct ? "RefSetter" : "Setter";
        string parameters = obj.IsStruct ? $"(ref {d} o, {t} v)" : "(o, v)";
        switch (m.Setter)
        {
            case SetterKind.Plain:
                Line($"{target} = static {parameters} => o.{Parser.CodeName(m.Name)} = v,");
                break;
            case SetterKind.InitOnly:
                string accessor = AddAccessor(m.DeclaringTypeName ?? d, t, m.Name, obj.IsStruct);
                Line(obj.IsStruct
                    ? $"{target} = static {parameters} => {accessor}(ref o, v),"
                    : $"{target} = static {parameters} => {accessor}(o, v),");
                break;
            default:
                // Filled through the constructor; reading into the argument slot needs no assignment.
                Line(obj.IsStruct ? $"{target} = static (ref {d} _, {t} _) => {{ }}," : $"{target} = static (_, _) => {{ }},");
                break;
        }

        CloseWith("}),");
    }

    // An init-only setter cannot be called from outside an initializer; the runtime can reach it by name.
    private string AddAccessor(string declaring, string valueType, string member, bool isStruct)
    {
        string name = "SetInit" + (++_accessorCount).ToString(CultureInfo.InvariantCulture);
        string self = isStruct ? $"ref {declaring}" : declaring;
        _accessors.Add((
            $"[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"set_{member}\")]",
            $"private static extern void {name}({self} instance, {valueType} value);"));
        return name;
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string Xml(string text) => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    // ---- Text ----

    private void Line(string text = "")
    {
        if (text.Length > 0)
        {
            _out.Append(' ', _indent * 4).Append(text);
        }

        _out.Append('\n');
    }

    private void Open()
    {
        Line("{");
        _indent++;
    }

    private void Close() => CloseWith("}");

    private void CloseWith(string text)
    {
        _indent--;
        Line(text);
    }
}
