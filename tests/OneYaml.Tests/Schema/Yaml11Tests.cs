using System.Text;
using OneYaml.Schema;
using Xunit;

namespace OneYaml.Tests.Schema;

public sealed class Yaml11Tests
{
    private static bool Looks(string s) => Yaml11.LooksNonString(Encoding.UTF8.GetBytes(s));

    [Theory]
    [InlineData("")]
    [InlineData("~")]
    [InlineData("null")]
    [InlineData("Null")]
    [InlineData("NULL")]
    [InlineData("nULL")]
    [InlineData("y")]
    [InlineData("Y")]
    [InlineData("n")]
    [InlineData("N")]
    [InlineData("yes")]
    [InlineData("Yes")]
    [InlineData("YES")]
    [InlineData("yEs")]
    [InlineData("no")]
    [InlineData("No")]
    [InlineData("NO")]
    [InlineData("on")]
    [InlineData("On")]
    [InlineData("ON")]
    [InlineData("off")]
    [InlineData("Off")]
    [InlineData("OFF")]
    [InlineData("true")]
    [InlineData("TRUE")]
    [InlineData("tRuE")]
    [InlineData("false")]
    [InlineData("False")]
    [InlineData("<<")]
    [InlineData("=")]
    [InlineData("12")]
    [InlineData("-12")]
    [InlineData("+12")]
    [InlineData("0")]
    [InlineData("0755")]
    [InlineData("00")]
    [InlineData("0o17")]
    [InlineData("0b1010")]
    [InlineData("0B11")]
    [InlineData("0x1F")]
    [InlineData("0X1f")]
    [InlineData("0x_1F")]
    [InlineData("1_000")]
    [InlineData("1_000.5")]
    [InlineData("-1_0")]
    [InlineData("1:30")]
    [InlineData("190:20:30")]
    [InlineData("685230:15")]
    [InlineData("1:30.5")]
    [InlineData("-1:30")]
    [InlineData("1.5")]
    [InlineData("1.")]
    [InlineData(".5")]
    [InlineData("-.5")]
    [InlineData("1e3")]
    [InlineData("1.5e+3")]
    [InlineData("6.02E+23")]
    [InlineData(".inf")]
    [InlineData(".Inf")]
    [InlineData(".INF")]
    [InlineData("-.inf")]
    [InlineData("+.inf")]
    [InlineData(".nan")]
    [InlineData(".NaN")]
    [InlineData(".iNf")]
    [InlineData("2001-12-14")]
    [InlineData("2001-1-4")]
    [InlineData("2001-12-14t21:59:43.10-05:00")]
    [InlineData("2001-12-14T21:59:43.10Z")]
    [InlineData("2001-12-14 21:59:43.10 -5")]
    public void Spellings_a_loose_reader_takes_as_non_strings(string text) => Assert.True(Looks(text), text);

    [Theory]
    [InlineData("hello")]
    [InlineData("yesterday")]
    [InlineData("no way")]
    [InlineData("nope")]
    [InlineData("on1")]
    [InlineData("offset")]
    [InlineData("nullable")]
    [InlineData("y1")]
    [InlineData("truth")]
    [InlineData("falsey")]
    [InlineData("x")]
    [InlineData("-")]
    [InlineData("+")]
    [InlineData(".")]
    [InlineData("-.")]
    [InlineData("1.5.2")]
    [InlineData("1:2:")]
    [InlineData("1:123")]
    [InlineData("1:")]
    [InlineData("12abc")]
    [InlineData("0x")]
    [InlineData("0xG")]
    [InlineData("0b")]
    [InlineData("e3")]
    [InlineData("1e")]
    [InlineData("1,000")]
    [InlineData("1 2")]
    [InlineData("2001-12-14foo")]
    [InlineData("2001-12-")]
    [InlineData("20011-12-14")]
    [InlineData("1-2")]
    [InlineData("<")]
    [InlineData("<<x")]
    [InlineData("==")]
    [InlineData("~x")]
    [InlineData("v1.2")]
    [InlineData("1.2.3")]
    [InlineData(".inf.")]
    [InlineData(".nano")]
    [InlineData("é")]
    [InlineData("a: b")]
    public void Ordinary_text_stays_a_string(string text) => Assert.False(Looks(text), text);

    [Fact]
    public void Everything_the_core_schema_reads_as_a_non_string_is_included()
    {
        foreach (string s in new[] { "", "~", "null", "true", "False", "12", "-0", "0o7", "0xFF", "1.5", ".5", "1e3", ".inf", "-.INF", ".nan" })
        {
            Assert.NotEqual(ScalarKind.String, CoreSchema.ResolvePlain(Encoding.UTF8.GetBytes(s)));
            Assert.True(Looks(s), s);
        }
    }

    // Spellings that Go's readers take as numbers: they drop every underscore, skip a second
    // sign, and accept a sign after the base prefix.
    [Theory]
    [InlineData("+_1")]
    [InlineData("-_6")]
    [InlineData("+__685")]
    [InlineData("-_1_53")]
    [InlineData("1e3_")]
    [InlineData("2E_0")]
    [InlineData("-3e_4")]
    [InlineData("8.E+_0")]
    [InlineData("0_x123")]
    [InlineData("9_E0_0")]
    [InlineData("3.e_5")]
    [InlineData("0o+7")]
    [InlineData("0x-1")]
    [InlineData("0o+157")]
    [InlineData("+-1")]
    [InlineData("++.4")]
    [InlineData("++1_.")]
    [InlineData("+-1._7")]
    [InlineData("++4.5")]
    public void Loose_readers_number_spellings_are_not_plain_strings(string text) => Assert.True(Looks(text), text);

    [Theory]
    [InlineData("--verbose")]
    [InlineData("-_")]
    [InlineData("+_x")]
    [InlineData("--")]
    [InlineData("1_a")]
    [InlineData("0o+")]
    [InlineData("-+x1")]
    public void Ordinary_text_with_signs_and_underscores_stays_plain(string text) => Assert.False(Looks(text), text);
}
